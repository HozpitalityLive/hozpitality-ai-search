def _job(
    n,
    title,
    city,
    country,
    company,
    description,
    *,
    keywords=None,
    level=None,
    days=0,
    extra=None,
):
    doc = {
        "_id": f"job:{n}",
        "entity_type": "job",
        "source": {"object_id": n},
        "title": title,
        "description": description,
        "search_keywords": keywords or [title.casefold(), "chef"]
        if "chef" in title.casefold()
        else keywords or [title.casefold()],
        "search_aliases": [],
        "location": {"city": city, "country": country},
        "company": {"name": company},
        "category": {
            "name": "Culinary" if "chef" in title.casefold() else "Hospitality"
        },
        "links": {"detail": f"{BASE}/jobs/{n}"},
        "ai_search_text": f"{title} {company} {city} {country['name']} {description}",
        "is_live": True,
        "status": "active",
        "created_at": NOW - timedelta(days=days),
        "metadata": {"job_level": level} if level else {},
    }
    if extra:
        doc.update(extra)
    return doc


